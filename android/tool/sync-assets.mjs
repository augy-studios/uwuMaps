#!/usr/bin/env node
// Copies what the app ships from main-site/ into android/assets/, so there's one copy to edit: the
// map's styles, sprites and fonts, and the public transport snapshots. Also writes the uwuapps icons
// into lib/theme/icon_paths.g.dart from main-site/js/icons.js. Run by build-apk.ps1, and by hand after
// tools/vendor-transit.mjs or a change to the icons.
//
//   node android/tool/sync-assets.mjs

import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const site = fileURLToPath(new URL('../../main-site/', import.meta.url));
const app = fileURLToPath(new URL('../', import.meta.url));

rmSync(`${app}assets/map`, { recursive: true, force: true });
rmSync(`${app}assets/data`, { recursive: true, force: true });
mkdirSync(`${app}assets`, { recursive: true });
cpSync(`${site}map`, `${app}assets/map`, { recursive: true });
cpSync(`${site}data`, `${app}assets/data`, { recursive: true });

const { icons } = await import(pathToFileURL(`${site}js/icons.js`).href);
const lines = Object.entries(icons).map(([name, svg]) => `  '${name}': r'''${svg}''',`);
writeFileSync(`${app}lib/theme/icon_paths.g.dart`, `// Generated by tool/sync-assets.mjs from main-site/js/icons.js. Don't edit.\n\nconst Map<String, String> uwuIconSvgs = {\n${lines.join('\n')}\n};\n`);
console.log('Assets and icons synced');
